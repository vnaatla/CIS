#!/usr/bin/env node
// Colour themes for src/styles.css.
//
//   node scripts/theme-tokens.cjs          rewrite styles.css: every brand colour (purple / magenta hues, incl. the purple-tinted greys)
//                                          becomes var(--tone-<hex>) with the same value, and the THEME TOKENS block at the end is regenerated
//   node scripts/theme-tokens.cjs --check  audit only: lists brand colours typed in outside the block (exit 1 if any)
//
// The default (purple) theme keeps every value exactly as designed. Another theme re-colours each tone by moving its hue (and scaling
// its saturation) while keeping its lightness, so every hand-tuned tint keeps its place in the design. Status colours (red / green /
// amber) and neutral greys are not brand colours and stay as they are. Data-URI images (the dropdown chevrons) cannot use variables,
// so their rules are repeated per theme with the colours converted.
// To add a theme: add it to THEMES, run the script, add it to ThemeService.
const fs = require('fs')
const path = require('path')

const FILE = path.join(__dirname, '..', 'src', 'styles.css')
const START = '/* ===== THEME TOKENS (generated by scripts/theme-tokens.cjs - do not edit by hand) ===== */'
const END = '/* ===== END THEME TOKENS ===== */'

/**
 * Each theme: target hue (degrees), a saturation factor and, optionally:
 * - `dark`: darker brand tones are darkened so that lightness `at` becomes `to` (the strong colour #7c2172 has lightness 0.31), easing
 *   back to unchanged at lightness `upTo` - tints and backgrounds stay light;
 * - `fixed`: tones given an exact value instead of the computed one.
 */
const THEMES = {
  // Navy blue: the strong colour becomes deep navy #0B2038; the accent (#9c2b8e) and its gradient partner (#a8329a) are set a little
  // brighter (`fixed`) so highlights, hover and the active tab still stand out from the strong colour.
  navy: { hue: 212, sat: 1.16, dark: { at: 0.3098, to: 0.1314, upTo: 0.75 }, fixed: { '9c2b8e': '1f4e8c', a8329a: '2a5c9e' } },
}

const hex2rgb = (h) => [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16))
const rgb2hex = (r, g, b) => [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('')
function rgb2hsl(r, g, b) {
  r /= 255; g /= 255; b /= 255
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2
  if (max === min) return [0, 0, l]
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min)
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4
  return [h * 60, s, l]
}
function hsl2rgb(h, s, l) {
  h /= 360
  if (s === 0) return [l * 255, l * 255, l * 255]
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s, p = 2 * l - q
  const f = (t) => { t = (t + 1) % 1; return t < 1 / 6 ? p + (q - p) * 6 * t : t < 1 / 2 ? q : t < 2 / 3 ? p + (q - p) * (2 / 3 - t) * 6 : p }
  return [f(h + 1 / 3) * 255, f(h) * 255, f(h - 1 / 3) * 255]
}
/** A brand colour: purple / magenta hue (270-345 degrees) with a visible tint. */
function isBrand(hex) {
  const [h, s] = rgb2hsl(...hex2rgb(hex))
  return s > 0.03 && h >= 270 && h <= 345
}
function convert(hex, theme) {
  if (theme.fixed?.[hex]) return theme.fixed[hex]
  const [, s, l] = rgb2hsl(...hex2rgb(hex))
  return rgb2hex(...hsl2rgb(theme.hue, Math.min(0.95, s * theme.sat), darken(l, s, theme.dark)))
}
/** Only real brand colours (saturation 25 %+) are darkened; the purple-tinted greys (label / secondary text) keep their lightness. */
function darken(l, s, d) {
  if (!d || l >= d.upTo || s < 0.25) return l
  const min = d.to / d.at
  const factor = l <= d.at ? min : min + ((l - d.at) / (d.upTo - d.at)) * (1 - min)
  return l * factor
}

let css = fs.readFileSync(FILE, 'utf8')
const eol = css.includes('\r\n') ? '\r\n' : '\n'
css = css.replace(/\r\n/g, '\n')
const blockAt = css.indexOf(START)
let body = blockAt >= 0 ? css.slice(0, blockAt).replace(/\n+$/, '\n') : css
const rest = blockAt >= 0 ? css.slice(css.indexOf(END) + END.length).replace(/^\n+/, '') : ''

const norm = (h) => (h.length === 3 ? [...h].map((c) => c + c).join('') : h).toLowerCase()
const literalHex = /#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b/g
const literalRgb = /rgba?\((\d{1,3})[ ,]+(\d{1,3})[ ,]+(\d{1,3})(\s*[/),])/g

if (process.argv.includes('--check')) {
  const found = []
  body.split('\n').forEach((line, i) => {
    for (const m of line.matchAll(literalHex)) if (isBrand(norm(m[1]))) found.push(`${i + 1}: #${m[1]}`)
    for (const m of line.matchAll(literalRgb)) if (isBrand(rgb2hex(+m[1], +m[2], +m[3]))) found.push(`${i + 1}: ${m[0]}`)
  })
  console.log(found.length ? `${found.length} brand colour(s) typed in outside the theme tokens:\n  ${found.join('\n  ')}` : 'theme audit: 0 brand colours typed in')
  process.exit(found.length ? 1 : 0)
}

const tones = new Set()
const rgbTones = new Set()
// Typed-in colours -> tokens (same value).
body = body.replace(literalHex, (m, h) => {
  const hex = norm(h)
  if (!isBrand(hex)) return m
  tones.add(hex)
  return `var(--tone-${hex})`
})
body = body.replace(literalRgb, (m, r, g, b, tail) => {
  const hex = rgb2hex(+r, +g, +b)
  if (!isBrand(hex)) return m
  rgbTones.add(hex)
  return `rgb(var(--tone-${hex}-rgb)${tail.includes(',') ? ' /' : tail}`
})
// Tokens already in use (re-runs).
for (const m of body.matchAll(/var\(--tone-([0-9a-f]{6})(-rgb)?\)/g)) (m[2] ? rgbTones : tones).add(m[1])

// Data-URI rules (chevrons): repeated per theme with converted colours.
const uriRules = []
for (const m of body.matchAll(/(^|\n)([^{}\n@][^{}]*?)\{([^{}]*%23[0-9a-fA-F]{6}[^{}]*)\}/g)) {
  const decls = m[3].split(';').map((d) => d.trim()).filter((d) => /url\(/.test(d) && /%23[0-9a-fA-F]{6}/.test(d))
  if (decls.some((d) => [...d.matchAll(/%23([0-9a-fA-F]{6})/g)].some((x) => isBrand(norm(x[1]))))) uriRules.push({ selectors: m[2].trim(), decls })
}

const sorted = (s) => [...s].sort()
const lines = [START, '/* Default (purple) theme: the designed values. */', ':root {']
for (const hex of sorted(tones)) lines.push(`  --tone-${hex}: #${hex};`)
for (const hex of sorted(rgbTones)) lines.push(`  --tone-${hex}-rgb: ${hex2rgb(hex).join(' ')};`)
lines.push('}')
for (const [name, theme] of Object.entries(THEMES)) {
  const sel = `:root[data-theme='${name}']`
  lines.push('', `/* ${name}: hue ${theme.hue}, saturation x${theme.sat}. */`, `${sel} {`)
  for (const hex of sorted(tones)) lines.push(`  --tone-${hex}: #${convert(hex, theme)};`)
  for (const hex of sorted(rgbTones)) lines.push(`  --tone-${hex}-rgb: ${hex2rgb(convert(hex, theme)).join(' ')};`)
  lines.push('}')
  for (const r of uriRules) {
    const selectors = r.selectors.split(',').map((s) => `${sel} ${s.trim()}`).join(',\n')
    const decls = r.decls.map((d) => d.replace(/%23([0-9a-fA-F]{6})/g, (x, h) => (isBrand(norm(h)) ? `%23${convert(norm(h), theme)}` : x)))
    lines.push(`${selectors} {\n  ${decls.join(';\n  ')};\n}`)
  }
}
lines.push(END)

const out = `${body}\n${lines.join('\n')}\n${rest ? '\n' + rest : ''}`
fs.writeFileSync(FILE, out.replace(/\n/g, eol))
console.log(`tones: ${tones.size}, rgb tones: ${rgbTones.size}, data-URI rules per theme: ${uriRules.length}, themes: ${Object.keys(THEMES).join(', ')}`)
