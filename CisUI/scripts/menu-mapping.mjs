// Generates Cis/docs/menu-mapping.md from src/app/layout/menu.ts and src/app/core/auth/access.ts.
// Usage (from CisUI): node scripts/menu-mapping.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const ui = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const access = Object.fromEntries([...readFileSync(path.join(ui, 'src/app/core/auth/access.ts'), 'utf8').matchAll(/^\s*(\w+):\s*(\d+),/gm)].map((m) => [m[1], +m[2]]))
const menu = readFileSync(path.join(ui, 'src/app/layout/menu.ts'), 'utf8')

const field = (text, name) => new RegExp(`${name}: '((?:[^'\\\\]|\\\\.)*)'`).exec(text)?.[1]
const modules = []
for (const block of menu.split(/\n  \{\n    key: /).slice(1)) {
  const label = field(block, 'label')
  const route = field(block, 'path')
  const items = [...block.matchAll(/\{ label: [^\n]+\}/g)].map(([line]) => ({
    label: field(line, 'label'),
    path: field(line, 'path'),
    access: access[/access: Access\.(\w+)/.exec(line)[1]],
    form: field(line, 'form'),
    group: field(line, 'group') ?? '',
    desktop: field(line, 'desktop') ?? 'visible',
    phase: +/phase: (\d+)/.exec(line)[1],
    migrated: /migrated: true/.test(line),
  }))
  modules.push({ label, route, items })
}

const state = { visible: '', hidden: 'Hidden (Visible = 0)', disabled: 'Disabled (Enabled = 0)', 'never-opened': 'Never opened', nothing: 'No handler, no form', empty: 'Form with no code', unavailable: 'Needs the SUN database (not available)', test: 'Developer test form' }
const all = modules.flatMap((m) => m.items)
const buildable = all.filter((i) => !['nothing', 'empty', 'unavailable', 'test'].includes(i.desktop))
const lines = [
  '# Menu mapping: VB6 `MDIMain.frm` → CIS web application',
  '',
  '> Generated by `node scripts/menu-mapping.mjs` (in `CisUI`) from `CisUI/src/app/layout/menu.ts` and `access.ts`. Do not edit by hand.',
  '',
  'Every menu item of the CIS desktop (`CIS VB/MDIMain.frm`), the VB6 form it opens (from its `*_Click` handler), the `CheckAccess` position,',
  'how the item appears in the desktop, the migration phase of the plan and the status. Scope is **everything** in `medixcis.vbp`: hidden,',
  'disabled and never-opened forms are migrated too. Pop-up forms opened from a screen (member / ICD / clinic search, case list, worksheet',
  'calculation, cheque / PV range print, ...) are listed with that screen.',
  '',
  `**${buildable.length} screens to build · ${buildable.filter((i) => i.migrated).length} migrated · ${all.length - buildable.length} menu items with no handler, no form, an empty form or a database that is not available (nothing to build).**`,
  '',
  '## Summary',
  '',
  '| Module | Screens | Migrated | Not in the desktop menu (hidden / disabled / never opened) |',
  '|---|---:|---:|---:|',
  ...modules.map((m) => {
    const b = m.items.filter((i) => !['nothing', 'empty', 'unavailable', 'test'].includes(i.desktop))
    return `| [${m.label}](#${m.label.toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/ /g, '-')}) | ${b.length} | ${b.filter((i) => i.migrated).length} | ${b.filter((i) => i.desktop !== 'visible').length} |`
  }),
  `| **Total** | **${buildable.length}** | **${buildable.filter((i) => i.migrated).length}** | **${buildable.filter((i) => i.desktop !== 'visible').length}** |`,
  '',
]
for (const m of modules) {
  lines.push(`## ${m.label}`, '', `Module page: \`${m.route}\``, '', '| Sub-menu | Menu item | VB6 form(s) | Access | Desktop | Phase | Status | Web route |', '|---|---|---|---:|---|---:|---|---|')
  for (const i of m.items)
    lines.push(
      `| ${i.group} | ${i.label} | ${i.form.replace(/\|/g, '\\|')} | ${i.access} | ${state[i.desktop]} | ${i.phase} | ${['nothing', 'empty', 'unavailable', 'test'].includes(i.desktop) ? 'Nothing to build' : i.migrated ? '**Migrated**' : 'Pending'} | \`${i.path}\` |`,
    )
  lines.push('')
}
lines.push(
  '## Not in this table',
  '',
  '- **File > Page Setup** (no handler) and **File > Print** (handler commented out): the topbar *Print* button prints the current screen; page setup is the browser\'s print dialog.',
  '- **Windows** (MDI window list): the browser\'s tabs / history replace it.',
  '- **Exit > Logout / Close Connection**: topbar *Log out* (USR.CIScnt - 1, as both desktop items did).',
  '- **frmLogin** and **MDIMain**: the login page and the app layout (Phase 0).',
  '- Forms in the `CIS VB` folder that are **not** in `medixcis.vbp` (old copies: frmDentalInvoice, frmInvDentalCln, frmInvoiceProcessing, ...): not part of the',
  '  project, not migrated unless the business asks (plan §6.6).',
  '',
)
writeFileSync(path.resolve(ui, '../Cis/docs/menu-mapping.md'), lines.join('\n'))
console.log(`menu-mapping.md: ${modules.length} modules, ${all.length} items`)
